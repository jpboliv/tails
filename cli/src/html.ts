/** One line of spec text rendered as GitHub would render it inline, with matched words marked. */
export const inlineMd = (s: string, mark: readonly string[] = [], ids?: ReadonlyMap<string, string>): string => renderInline(s, { mark, ...(ids ? { ids } : {}) });

export function rel(from: string, to: string): string {
  const r = posix.relative(posix.dirname(from), to);
  return (r === "" ? posix.basename(to) : r).split("/").map(encodeURIComponent).join("/");
}

export type Tone = "fail" | "warn" | "ok" | "info" | "neutral";

export const chip = (tone: Tone, label: string, title?: string): string =>
  `<span class="chip ${tone}"${title ? ` title="${esc(title)}"` : ""}>${esc(label)}</span>`;

export interface Crumb {
  readonly label: string;
  readonly href?: string;
}

export type Section = "overview" | "findings" | "docs" | null;

export interface PageOptions {
  readonly path: string;
  readonly title: string;
  readonly section: Section;
  readonly crumbs?: readonly Crumb[];
  readonly body: string;
  /** What the report was read from: a commit, refs, or the working tree. */
  readonly source: string;
  /** A sidebar beside the content on wide screens, such as a document's section tree. */
  readonly aside?: string;
  /** The Overview, Findings and Documents landing pages. */
  readonly workspace?: boolean;
}

