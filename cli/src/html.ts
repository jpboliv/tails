export function page(o: PageOptions): string {
  const link = (to: string, label: string, key: Section) =>
    `<a href="${rel(o.path, to)}"${o.section === key ? ' aria-current="page"' : ""}>${key ? icon(key) : ""}${label}</a>`;
  const crumbs = o.crumbs?.length
    ? `<nav class="crumbs" aria-label="Breadcrumb"><ol>${o.crumbs.map((c) => `<li>${c.href ? `<a href="${rel(o.path, c.href)}">${esc(c.label)}</a>` : `<span aria-current="page">${esc(c.label)}</span>`}</li>`).join("")}</ol></nav>`
    : "";
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>${esc(o.title)} · tails</title>
<script>${HEAD_JS}</script>
<style>${CSS}${WORKSPACE_CSS}</style>
</head>
<body${o.workspace ? ' class="workspace"' : ""}>
<a class="skip" href="#main">Skip to content</a>
<header class="appbar">
<a class="brand" href="${rel(o.path, "index.html")}">${MARK}<span>tails</span></a>
<nav class="primary" aria-label="Report">${link("index.html", "Overview", "overview")}${link("drift.html", "Findings", "findings")}${link("docs.html", "Documents", "docs")}</nav>
<span class="spacer"></span>
<span class="source" title="What this report was read from">${o.source}</span>
<button class="theme" type="button" hidden data-theme-toggle aria-label="Colour theme: follows the system">Auto</button>
</header>
${o.aside ? `<main id="main" class="has-aside"><aside class="docnav">${o.aside}</aside><div class="main-col">\n${crumbs}\n${o.body}\n</div></main>` : `<main id="main">\n${crumbs}\n${o.body}\n</main>`}
${FOOT}
<script>${BODY_JS}${DOCUMENT_NAV_JS}${o.workspace ? BROWSE_JS : ""}</script>
</body>
</html>
`;
}

